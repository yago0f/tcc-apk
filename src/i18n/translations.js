function getByPath(object, path) {
  return path.split('.').reduce((current, key) => current?.[key], object);
}

export function translate(language, key, params = {}) {
  const selected = TRANSLATIONS[language] || TRANSLATIONS.pt;
  const fallback = TRANSLATIONS.pt;
  const value = getByPath(selected, key) ?? getByPath(fallback, key) ?? key;

  if (typeof value !== 'string') {
    return key;
  }

  return Object.entries(params).reduce(
    (text, [param, replacement]) => text.replaceAll(`{{${param}}}`, String(replacement)),
    value,
  );
}
